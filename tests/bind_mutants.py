def _between(path, start, end):
    """The exact text of ``path`` from ``start`` up to and including ``end`` (read at import, so the mutant follows
    the file)."""
    text = (ROOT / path).read_text(encoding="utf-8")
    i = text.index(start)
    j = text.index(end, i) + len(end)
    return text[i:j]


