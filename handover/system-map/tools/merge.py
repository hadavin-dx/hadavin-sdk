"""Mechanical merge of lane files into MASTER-MAP.md and the Findings part of SWEEP.md (PLAN-002 section 5).
Usage: python3 tools/merge.py <system-map dir>. Rows keep their lane ids. No judging: only grouping and sorting."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from safe_write import safe_write

LANES = ["L1", "L1c", "L2", "L2c", "L3", "L3c", "L4", "L4c", "L5a", "L5ac", "L5b", "L6"]
KIND = {"C": "Components", "P": "Ports and hosts", "A": "Agents and sessions", "R": "Repos and branches",
        "S": "Stores", "W": "Workflows", "WK": "Workflow walk", "X": "Scripts", "J": "Jobs",
        "K": "Credentials", "D": "Docs", "T": "Tests", "F": "Folders"}
ORDER = ["Components", "Stores", "Workflows", "Workflow walk", "Scripts", "Jobs", "Credentials", "Ports and hosts",
         "Agents and sessions", "Repos and branches", "Docs", "Tests", "Folders"]
SECT = ["Components", "Stores", "Workflows", "Workflow walk", "Scripts", "Jobs", "Credentials", "Docs and tests and folders"]


def parse(path):
    sec, hdr, out = None, None, {}
    for line in open(path, encoding="utf-8", errors="replace"):
        line = line.rstrip("\n")
        if line.startswith("## "):
            sec, hdr = line[3:].strip(), None
        elif sec and line.startswith("|"):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if hdr is None:
                hdr = cells
                out.setdefault(sec, {})[tuple(hdr)] = []
            elif not set("".join(cells)) <= set("-: "):
                out[sec][tuple(hdr)].append(cells)
    return out


def kind_of(row_id):
    m = re.match(r"L\d\w*?-([A-Z]+)-\d+", row_id)
    return m.group(1) if m else None


def main(base, force=False):
    work = os.path.join(base, "work")
    groups, findings, skipped = {}, [], []
    dropped = []
    names = list(LANES) + sorted(f[:-3] for f in os.listdir(work) if re.fullmatch(r"L\d\w*\.md", f) and f[:-3] not in LANES)
    for lane in names:
        p = os.path.join(work, lane + ".md")
        if not os.path.exists(p):
            continue
        d = parse(p)
        for sec in d:
            if sec in ("Findings", "Coverage") or not re.match(r"L\d", "L1"):
                continue
            for hdr, rows in d[sec].items():
                for r in rows:
                    if not (r and re.match(r"L\d\w*?-[A-Z]+-\d+", r[0])):
                        continue  # header-like or free text row
                    k = kind_of(r[0])
                    target = KIND.get(k)
                    if target and sec in SECT:
                        groups.setdefault(target, {}).setdefault(hdr, []).append(r)
                    else:
                        dropped.append(f"{lane}: {r[0]} under '## {sec}' (kind {k})")
        for hdr, rows in d.get("Findings", {}).items():
            findings += [(hdr, r) for r in rows if len(r) == len(hdr)]
            skipped += [lane + ": " + (r[0] if r else "?") for r in rows if len(r) != len(hdr)]
    out = ["# MASTER MAP (generated by tools/merge.py from work/L*.md; rows keep their lane ids; evidence is in each row)", ""]
    n = 0
    for sec in ORDER:
        out += [f"## {sec}", ""]
        blocks = groups.get(sec, {})
        if not blocks:
            out += [f"NONE FOUND: no lane row of this kind", ""]
        for hdr, rows in blocks.items():
            out += ["| " + " | ".join(hdr) + " |", "|" + "---|" * len(hdr)]
            out += ["| " + " | ".join(r) + " |" for r in rows]
            out += [""]
            n += len(rows)
    out += ["## Not visible or out of scope", "",
            "| id | name | purpose | evidence | job keys |", "|---|---|---|---|---|",
            "| TAKE-REPO | duplicate-proof-lead-desk take code repo | NOT VISIBLE in this box (local only by owner rule); lead covers locally; content not guessed | NOT VISIBLE: duplicate-proof-lead-desk | none |",
            "| CORE | src/ and tests/ (shared core hadavin_sdk) | out of take scope; not mapped module by module; directory list and README only | NOT VISIBLE: see L5b CORE row | none |",
            "| UNTRACKED | untracked or ignored files | out of scope: lanes read `git ls-files` only | N/A: scope rule | none |", ""]
    add = os.path.join(base, "hand-kept", "MAP-ADDITIONS.md")
    if os.path.exists(add):
        out += open(add).read().split("\n")
    if not safe_write(base, "MASTER-MAP.md", "\n".join(out), force):
        print("REFUSED: MASTER-MAP.md was edited by hand or has no record of being generated; nothing written; use --force"); return 1
    sev = {"Blocker": 0, "Major": 1, "Nit": 2}
    findings.sort(key=lambda hr: (sev.get(hr[1][2], 3), hr[1][0]))
    cols = "| id | claim type | severity | evidence | conflicts with | job key |"
    fl = ["## Findings", "", cols, "|---|---|---|---|---|---|"]
    counts = {}
    for hdr, r in findings:
        fl.append("| " + " | ".join(r) + " |")
        counts[(r[1], r[2])] = counts.get((r[1], r[2]), 0) + 1
    if not safe_write(base, os.path.join("work", "merged-findings.md"), "\n".join(fl) + "\n", force):
        print("REFUSED: work/merged-findings.md was edited by hand; use --force"); return 1
    print("rows", n, "findings", len(findings))
    for x in dropped:
        print("DROPPED", x)
    types = sorted({k[0] for k in counts})
    print({t: {s: counts.get((t, s), 0) for s in ("Blocker", "Major", "Nit")} for t in types})
    for x in skipped:
        print("SKIPPED finding row (wrong cell count)", x)
    return 1 if (dropped or skipped) else 0


if __name__ == "__main__":
    _a = [a for a in sys.argv[1:] if not a.startswith("--")]
    sys.exit(main(_a[0], force="--force" in sys.argv))
