"""Writes TAKE-USED-FILES-r7t.md and test_take_imports.py from the static closure (take_closure.py; nothing is run).
usage (r7t: the first tree is r7t, the second is r7s): python -I gen_take.py <tree-r7t> <tree-r7s> <tree-r7n> <tree-r7p> <out dir>"""

from __future__ import annotations

import filecmp
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import take_closure as tc  # noqa: E402


def main() -> None:
    r7r, r7s, r7n, r7p, out = (Path(a).resolve() for a in sys.argv[1:6])
    files_r, pairs_r, notes_r = tc.walk(r7r)
    files_s, pairs_s, notes_s = tc.walk(r7s)

    def changed(rel: str, other: Path) -> str:
        a, b = r7r / rel, other / rel
        if not b.is_file():
            return "NEW (not in " + other.name.replace("tree-", "") + ")"
        return "same" if filecmp.cmp(a, b, shallow=False) else "CHANGED"

    lines = [
        "# Take used-core-files list for r7t (regenerated by a script; replaces the r7r/r7s list)",
        "",
        "Written by the r7t builder (order C-R7T-ADD, minor 6). Computed from the r7t tree by `take_closure.py` "
        "(python `ast`, reads text only, nothing of the repository is run).",
        "Entry points: scripts/run_real_check.py and scripts/crash_desk.py (the child process the real check starts with "
        "sys.executable, run_real_check.py about line 833). The walk follows `import x`, `from x import y` (module level "
        "and inside functions), relative imports and literal strings given to importlib.import_module.",
        "",
        f"Result: {len(files_r)} files in the closure; {len(pairs_r)} (module, name) pairs are imported from them.",
        "",
        "## What the earlier list (cut from the r7n patch, 162 files) got wrong or left open",
        "",
        "- Its UNVERIFIED rows are resolved. demo_only/fakes_server.py: NOT in the closure (imported by no file of the "
        "closure; only tests/conftest.py and the text of tools/refusing_args.py name it). src/lead_desk/trace.py: NOT in "
        "the closure (no import of it from any closure file; the only `trace` import is the standard module `traceback` "
        "in scrub.py). demo_only/fake_model_server.py is also NOT in the closure (the earlier list said yes, that was wrong: "
        "DryFakes in run_real_check.py uses fake_hubspot, fake_imap and fake_smtp_tls only; a live run uses the real model "
        "host). demo_only/burst.py IS in the closure (imported by demo_only/portal_demo.py), the earlier list said no.",
        "- The row `demo_only/bad_request.py: NO counterpart, not checked` was a real gap: demo_only/fake_hubspot.py imports "
        "`QuietServer` from it, so a take base without that file cannot start the dry fakes at all (import error). It is now "
        "in the closure and in the name list below.",
        "- Dynamic imports: loader.py imports by a literal string `demo_only.fakes` (twice) and `demo_only.portal_demo` "
        "(followed); `_kind_module(name)` takes `HUBSPOT_MODULE`, `SMTP_MODULE` or `SMTP_PROVIDER_MODULE` "
        "(constants.py lines 148, 150, 185: lead_desk.crm_hubspot, lead_desk.smtp_outbox, lead_desk.smtp_provider), all of "
        "which are in the closure through static imports.",
        "- Not covered by the walk (stated, not hidden): non-Python runtime files (schema.sql, demo_only/*.json, portal "
        "assets), anything run as a separate command (scripts other than the two entry points), and names reached by "
        "`getattr` with a built string. A star import would be listed below as a note; there is none.",
        "",
        "## Files in the closure",
        "",
        "`vs r7n` and `vs r7p` compare the r7r file with the same path in those trees (the take was cut from the r7n "
        "patch, so CHANGED/NEW against r7n are the files the take must receive).",
        "",
        "| file | why it is in the closure | vs r7n | vs r7p |",
        "|---|---|---|---|",
    ]
    for f in sorted(files_r):
        lines.append(f"| {f} | {files_r[f]} | {changed(f, r7n)} | {changed(f, r7p)} |")
    lines += ["", "Notes from the walk:", ""]
    lines += [f"- {n}" for n in notes_r] or ["- none"]

    def has(tree: Path, mod: str, name: str) -> bool:
        f = tc.module_file(tree, mod)
        return bool(f) and name in tc.top_level_names(f)

    missing_n = [(m, n) for m, n in sorted(pairs_r) if not has(r7n, m, n)]
    missing_p = [(m, n) for m, n in sorted(pairs_r) if not has(r7p, m, n)]
    lines += [
        "",
        "## Names the take base must export (module: name), checked in the r7t tree",
        "",
        f"All {len(pairs_r)} pairs exist in r7t (checked: each name is bound at the top level of its module). Absent in "
        f"the r7n tree: {', '.join(f'{m}.{n}' for m, n in missing_n) or 'none'}. Absent in the r7p tree: "
        f"{', '.join(f'{m}.{n}' for m, n in missing_p) or 'none'}.",
        "The names r7q added on the take path are all in the list (identity.normalise_email, constants.LEAD_ID_PREFIX, "
        "constants.LEAD_ID_HEX_CHARS, constants.MODEL_CALLS_PER_LEAD_MAX, live_claude.question_text, "
        "live_claude.request_body, live_claude.worst_case_usd, bad_request.QuietServer). Whether the TAKE base has them was "
        "not checkable from here (the take tree is not on this machine): the file `test_take_imports.py` imports every "
        "pair and is for the lead to run on the take tree.",
        "",
    ]
    by_mod: dict[str, list[str]] = {}
    for m, n in sorted(pairs_r):
        by_mod.setdefault(m, []).append(n)
    for m in sorted(by_mod):
        lines.append(f"- `{m}`: " + ", ".join(f"`{n}`" for n in by_mod[m]))
    added = sorted(pairs_r - pairs_s)
    lines += [
        "",
        "## Added by r7t (not in r7s)",
        "",
        (", ".join(f"`{m}.{n}`" for m, n in added) or "no new pair")
        + ". Also new in r7t and used by the take path: `run_real_check.CounterRead`, `read_counter_files_checked`, "
        "`counter_is_known`, `CounterUnreadable`, `desk_port`, `exit_code_of(..., counter_known)` (fifth argument), "
        "`Desk(..., tag)` (tag required) and `demo_only.bad_request.require_loopback_host`; the mail fakes now import "
        "demo_only.bad_request (test_take_imports.py checks these).",
        "",
    ]
    (out / "TAKE-USED-FILES-r7t.md").write_text("\n".join(lines) + "\n", encoding="utf-8")

    all_pairs = sorted(pairs_s | pairs_r)
    body = [
        '"""Take-side import test (r7t; orders C-R7S item 2 and C-R7T-ADD minor 6). Run it on the TAKE tree (the r7t patch applied):',
        "every (module, name) pair the take entry points import from the repository must be importable there. A missing",
        "name is one failed item with its name. Generated from the static closure of scripts/run_real_check.py and",
        "scripts/crash_desk.py (take_closure.py); on the r7p tree it fails for the names r7p lacks (r7q, r7s additions).",
        "",
        "Run: PYTHONPATH=<tree>/src python -m pytest -q -p no:cacheprovider <this file>   (from the tree root, so that",
        'the folders `scripts`, `tools`, `demo_only`, `load_tools` are importable; the test puts the root on the path)."""',
        "",
        "from __future__ import annotations",
        "",
        "import importlib",
        "import inspect",
        "import sys",
        "from pathlib import Path",
        "",
        "import pytest",
        "",
        "ROOT = Path(__file__).resolve().parents[1]",
        "if not (ROOT / 'scripts').is_dir() or not (ROOT / 'src').is_dir():",
        "    raise RuntimeError(f'test_take_imports.py must sit in <tree>/tests (found no scripts and src folder in {ROOT})')",
        "for p in (ROOT / 'src', ROOT / 'scripts', ROOT):",
        "    if str(p) not in sys.path:",
        "        sys.path.insert(0, str(p))",
        "",
        "PAIRS = [",
    ]
    body += [f"    ({m!r}, {n!r})," for m, n in all_pairs]
    body += [
        "]",
        "",
        "",
        '@pytest.mark.parametrize(("module", "name"), PAIRS, ids=[f"{m}:{n}" for m, n in PAIRS])',
        "def test_every_name_the_take_run_imports_exists(module: str, name: str) -> None:",
        "    mod = importlib.import_module(module)",
        "    assert hasattr(mod, name), f'{module} has no {name}'",
        "",
        "",
        "def test_run_real_check_has_the_r7t_counter_rules() -> None:",
        "    rrc = importlib.import_module('run_real_check')",
        "    assert hasattr(rrc, 'contacts_not_accounted_for'), 'run_real_check.contacts_not_accounted_for is missing'",
        "    assert 'tag' in inspect.signature(rrc.read_counter_files).parameters, 'read_counter_files has no tag'",
        "    params = inspect.signature(rrc.Desk.__init__).parameters",
        "    assert 'tag' in params and params['tag'].default is inspect.Parameter.empty, 'Desk tag is missing or optional'",
        "    for name in ('CounterRead', 'CounterUnreadable', 'counter_is_known', 'read_counter_files_checked', 'desk_port'):",
        "        assert hasattr(rrc, name), f'run_real_check.{name} is missing'",
        "    assert 'counter_known' in inspect.signature(rrc.exit_code_of).parameters, 'exit_code_of has no counter_known'",
        "    assert hasattr(importlib.import_module('demo_only.bad_request'), 'require_loopback_host')",
        "",
    ]
    (out / "test_take_imports.py").write_text("\n".join(body), encoding="utf-8")
    print(len(files_r), len(pairs_r), len(all_pairs), "missing in r7n:", missing_n, "missing in r7p:", missing_p)


if __name__ == "__main__":
    main()
