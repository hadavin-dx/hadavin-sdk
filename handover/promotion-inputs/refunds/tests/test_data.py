def test_world_invariants_and_synthetic_only():
    w = json.loads((DATA / "world.json").read_text(encoding="utf-8"))
    for o in w["orders"]:
        ls = sum(int(x["unit_minor"]) * x["qty"] for x in o["lines"])
        assert int(o["captured_minor"]) == ls + int(o["shipping_minor"]) and int(o["refunded_minor"]) <= int(o["captured_minor"])
        assert int(o["refunded_minor"]) == sum(int(x["refunded_minor"]) for x in o["lines"]) + int(o["shipping_refunded_minor"])
        assert all(int(x["refunded_minor"]) <= int(x["unit_minor"]) * x["qty"] for x in o["lines"])
        assert sum(int(f["amount_minor"]) for f in o["refunds"]) == int(o["refunded_minor"]) and o["currency"] in config.LIMITS
        assert o["dispute_status"] in ("none", "open", "lost") and set(o["ship_to"]) == {"name", "line1", "postcode", "country"}
        assert all(
            set(a) >= {"kind", "amount_minor", "ts", "line_ids"} and a["kind"] in ("reship", "goodwill", "cancel")
            for a in o["other_actions"]
        )
    emails = [c["email"] for c in w["customers"]]
    assert len(set(emails)) == len(emails) and all(e.lower().endswith("@example.com") for e in emails)
    raw = "".join(
        (DATA / n).read_text(encoding="utf-8") for n in ("world.json", "dev.jsonl", "isolation.json", "burst_plan.json")
    )
    assert raw.isascii() and not re.search(r"@(?!example\.com)[\w.-]+\.\w+", raw, re.IGNORECASE)


