def test_dev_world_order_timelines_are_possible():
    """placed <= shipped <= delivered, the carrier ETA is not before placement, and no refund predates placement or delivery
    (the generator once moved the ETA or the refund without moving the order dates). The test world is checked in tests_oneshot."""
    world = json.loads((DATA / "world.json").read_text(encoding="utf-8"))
    bad = []
    for o in world["orders"]:
        chain = [(k, o[k]) for k in ("placed_at", "shipped_at", "delivered_at") if o.get(k)]
        bad += [(o["order_id"], a, b) for (a, x), (b, y) in itertools.pairwise(chain) if x > y]
        if o.get("carrier_eta") and o["carrier_eta"] < o["placed_at"]:
            bad.append((o["order_id"], "carrier_eta", "placed_at"))
        for r in o["refunds"]:
            if r["ts"] < o["placed_at"] or (o.get("delivered_at") and r["ts"] < o["delivered_at"]):
                bad.append((o["order_id"], "refund", r["refund_id"]))
    assert bad == []
