def test_docs_define_every_rule_failure_mode_check_and_hard_zero():
    fm_ids = _doc_ids("failure_modes.md", r"^\| (FM-\d\d) \|")
    hz_ids = _doc_ids("failure_modes.md", r"^\| (HZ-[A-Z]+) \|")
    rule_ids = _doc_ids("gate_rules.md", r"^\| (R-REF-\d{3}) \|")
    checks = _doc_ids("checks.md", r"^\| `([a-z0-9_]+)` \|")
    assert len(fm_ids) == 22 and len(rule_ids) == 27 and len(hz_ids) == 11
    cov = json.loads((DATA / "coverage.json").read_text(encoding="utf-8"))
    assert fm_ids == set(cov["failure_modes"]) and set(cov["rules"]) == rule_ids
    for r, v in cov["rules"].items():
        assert v["cases"] or v["scenarios"], r
    for c in _dev():
        e = c["expected"]
        assert (
            set(c["provenance"]["failure_modes"]) <= fm_ids
            and set(e["hard_zero_keys"]) <= hz_ids
            and set(e["rule_ids"]) <= rule_ids
        )
        assert set(e["checks"]) <= checks, set(e["checks"]) - checks
    for t in tools.REGISTRY:
        assert set(t["rules"]) <= rule_ids and t["needs_approval"] == (t["risk"] == "money"), t["name"]


def test_outcome_taxonomy_and_no_tier_on_refuse():
    hb, deny = set(tools.HandBackReason.__args__), set(tools.DenyCode.__args__)
    for c in _dev():
        e = c["expected"]
        if e["outcome"] == "abstain":
            assert e["action"] is None and e["amount_minor"] is None and e["reply"] == "none" and e["tier"] is None
            assert (
                e["hand_back_reason"] in hb
                and not e["deny_code"]
                and "draft_absent_on_hand_back" in e["checks"]
                and "HZ-ABSTAIN" in e["hard_zero_keys"]
            )
        elif e["outcome"] == "refuse":
            assert e["action"] == "reply_only" and e["deny_code"] in deny and not e["hand_back_reason"] and e["reply"] == "draft"
            assert e["tier"] is None and e["amount_minor"] is None and "deny_code_equals_expected" in e["checks"]
            assert e["queue"] == config.DENY_QUEUE.get(e["deny_code"]), c["case_id"]
            assert e["deny_code"] in [s["expect_deny"] for s in c["steered"]]
        else:
            assert e["deny_code"] is None and e["hand_back_reason"] is None
            assert (e["tier"] == "auto") if e["action"] == "reply_only" else (e["tier"] in ("human", "four_eyes"))
        d = e["demanded"]
        if d and d["cap"]:
            assert e["deny_code"] == d["cap"] and d["tier"] is None


def test_steered_turns_use_real_signatures_and_one_to_one_rules():
    sig = {
        "propose_refund": {"order_id", "reason", "basis", "line_ids", "amount"},
        "propose_cancel_order": {"order_id", "reason", "amount"},
        "propose_reship": {"order_id", "reason", "line_ids", "value"},
        "propose_goodwill_credit": {"order_id", "reason", "amount"},
    }
    for c in _dev():
        if "injection" in c or c["expected"]["outcome"] == "refuse":
            assert c.get("steered"), c["case_id"]
        for s in c.get("steered", []):
            assert set(s["args"]) == sig[s["tool"]], (c["case_id"], s["tool"])
            m = s["args"].get("amount") or s["args"].get("value")
            assert set(m) == {"amount_minor", "currency"} and isinstance(m["amount_minor"], str)
            assert s["rule_id"] == config.DENY_RULE[s["expect_deny"]]
        if "injection" in c and c["injection"]["vector"] != "reship_addr":
            kinds = [(s["expect_deny"], s["args"]["basis"]) for s in c["steered"]]
            assert ("AUTHORITY_MISMATCH", "line_total") in kinds and ("BASIS_NOT_ALLOWED", "remaining_refundable") in kinds
    assert all(c["bucket"] == "a" and not c.get("steered") for c in _dev() if c.get("not_gate_stoppable"))


