"""Build one self-contained console page: `python build_console.py <export.json> [-o index.html]`.

The export is validated against the schema, then embedded in the page (works from file://, no fetch). The
embedding is escaped for a script element: every `<`, `>` and `&` becomes a unicode escape, so `</script>` or `<!--`
inside any text cannot end the element. Inline script and style are allowed by SHA-256 hash in a strict CSP;
there is no `unsafe-inline`, no remote source of any kind.
"""

from __future__ import annotations

import argparse
import base64
import hashlib
import html
import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent))

from hadavin_kit import strict_json
from hadavin_kit.validate import validate as validate_export


def _hash(text: str) -> str:
    return (
        "'sha256-" + base64.b64encode(hashlib.sha256(text.encode("utf-8")).digest()).decode() + "'"
    )


def embed_json(doc: dict) -> str:
    text = json.dumps(doc, ensure_ascii=True, separators=(",", ":"), allow_nan=False)
    return text.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")


def validate(doc: dict, *, rules: bool = True) -> None:
    """`rules=False` skips ALL validation: a test hook to build hand-made, deliberately invalid pages. The CLI never uses it."""
    if not rules:
        return
    found = validate_export(doc)
    shape = [
        p
        for p in found
        if p.code not in ("RULE", "CHAIN", "MINOR_TOO_LOW", "BAD_CHARACTER")
        and not (p.code == "OVERSIZE" and not p.path)
    ]
    if shape:
        first = "; ".join(f"{p.path or '<root>'}: {p.message[:120]}" for p in shape[:5])
        raise ValueError(f"export does not match hadavin.demo-export/1: {first}")
    if found:
        raise ValueError(
            "export breaks a cross-field rule: " + "; ".join(p.message for p in found[:5])
        )


def csp_for(js: str, css: str) -> str:
    """The one CSP string: the meta tag uses it as is, the _headers file adds frame-ancestors (not allowed in a meta tag)."""
    return (
        f"default-src 'none'; script-src {_hash(js)}; style-src {_hash(css)}; base-uri 'none'; "
        "form-action 'none'; object-src 'none'; require-trusted-types-for 'script'"
    )


def headers_file(csp: str) -> str:
    return chr(10).join(
        [
            "# Generated by build_console.py with the same CSP hashes as the page's meta tag. Do not edit.",
            "/*",
            f"  Content-Security-Policy: {csp}; frame-ancestors 'none'",
            "  X-Content-Type-Options: nosniff",
            "  Referrer-Policy: no-referrer",
            "  X-Frame-Options: DENY",
            "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()",
            "  Cross-Origin-Opener-Policy: same-origin",
            "  Cross-Origin-Resource-Policy: same-origin",
            "  Strict-Transport-Security: max-age=31536000",
            "  Cache-Control: no-cache",
            "  X-Robots-Tag: noindex",
            "",
        ]
    )


def assets() -> tuple[str, str, str]:
    template = (HERE / "index.template.html").read_text(encoding="utf-8")
    css = (HERE / "app.css").read_text(encoding="utf-8")
    js = (
        (HERE / "chain.js").read_text(encoding="utf-8")
        + chr(10)
        + (HERE / "app.js").read_text(encoding="utf-8")
    )
    return template, css, js


def build(doc: dict, *, rules: bool = True) -> str:
    validate(doc, rules=rules)
    template, css, js = assets()
    for part in (css, js):
        if any(t in part for t in ("__DATA__", "__CSP__", "__TITLE__", "__JS__", "__CSS__")):
            raise ValueError("a console source file contains a template placeholder")
    csp = csp_for(js, css)
    title = html.escape(f"{doc['demo']['title']} - Hadavin demo console", quote=True)
    # Placeholders are replaced in one pass over the template so inserted text is never re-scanned.
    parts = {
        "__CSP__": csp,
        "__TITLE__": title,
        "__CSS__": css,
        "__DATA__": embed_json(doc),
        "__JS__": js,
    }
    out, rest = [], template
    while rest:
        hits = [(rest.find(k), k) for k in parts if k in rest]
        if not hits:
            out.append(rest)
            break
        i, k = min(hits)
        out.append(rest[:i])
        out.append(parts[k])
        rest = rest[i + len(k) :]
    return "".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("export", type=Path)
    ap.add_argument("-o", "--out", type=Path, default=None)
    ap.add_argument(
        "--no-headers", action="store_true", help="do not write the _headers file next to the page"
    )
    args = ap.parse_args(argv)
    try:
        page = build(strict_json.load_object(args.export))
    except (OSError, ValueError, RecursionError) as err:
        print(f"error: {type(err).__name__}: {err}", file=sys.stderr)
        return 2
    out = args.out or args.export.with_name("index.html")
    out.write_text(page, encoding="utf-8", newline=chr(10))
    if not args.no_headers:
        _, css, js = assets()
        out.with_name("_headers").write_text(
            headers_file(csp_for(js, css)), encoding="utf-8", newline=chr(10)
        )
    print(out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
