"""Regenerate src/intake/confusables_data.py from the Unicode UTS #39 file confusables.txt (a local copy; this tool never downloads).

Usage:  python tools/gen_confusables_wp3.py <path to confusables.txt> [--write] [--check]
  (no flag) print the module text;  --write  overwrite src/intake/confusables_data.py;  --check  exit 1 if the committed data differs.
The source file is fetched by hand from https://www.unicode.org/Public/security/latest/confusables.txt; its sha256 and version header are
pinned in the generated module (SOURCE_SHA256, SOURCE_VERSION). A different version header stops the tool: review the new data first.
Filter: type MA lines whose source is ONE non-ASCII code point and whose target is ONE ASCII letter or digit (lower-cased).
"""

import hashlib
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "src" / "intake" / "confusables_data.py"
PINNED_VERSION = "18.0.0"
SOURCE_URL = "https://www.unicode.org/Public/security/latest/confusables.txt"


def parse(text: str) -> tuple[dict[int, str], str, str]:
    """(table, version, date) from the text of confusables.txt; raises ValueError when the version differs from the pinned one."""
    version = re.search(r"^# Version: (\S+)", text, re.M)
    date = re.search(r"^# Date: (.+)$", text, re.M)
    if not version or version.group(1) != PINNED_VERSION:
        raise ValueError(f"confusables.txt version {version.group(1) if version else None!r} is not the pinned {PINNED_VERSION}")
    pairs: dict[int, str] = {}
    for line in text.splitlines():
        if line.startswith("#") or ";" not in line:
            continue
        parts = [p.strip() for p in line.split("#")[0].split(";")]
        if len(parts) < 3 or parts[2] != "MA":
            continue
        src, tgt = parts[0].split(), parts[1].split()
        if len(src) != 1 or len(tgt) != 1:
            continue
        s, t = int(src[0], 16), int(tgt[0], 16)
        c = chr(t)
        if s >= 0x80 and c.isascii() and c.isalnum():
            pairs[s] = c.lower()
    return pairs, version.group(1), (date.group(1).strip() if date else "")


def render(pairs: dict[int, str], version: str, date: str, sha: str) -> str:
    items = [f"{k:x}:{v}" for k, v in sorted(pairs.items())]
    lines = [" ".join(items[i : i + 14]) for i in range(0, len(items), 14)]
    body = "\n".join(f'    "{x} "' for x in lines)
    return f'''"""Single-character Latin/digit look-alikes, generated from the Unicode confusables data (kept as data, not hand-written).

GENERATED by tools/gen_confusables_wp3.py. Do not edit; change the generator and regenerate.
Source: {SOURCE_URL}
Version {version}, dated {date}; sha256 of the file {sha}.
Filter: type MA lines whose source is ONE non-ASCII code point and whose target is ONE ASCII letter or digit (lower-cased); {len(pairs)} entries.

Unicode License v3 notice: (c) Unicode, Inc. Data files and software are used under the Unicode License v3,
https://www.unicode.org/terms_of_use.html . Unicode and the Unicode Logo are registered trademarks of Unicode, Inc.
"""

SOURCE_URL = "{SOURCE_URL}"
SOURCE_VERSION = "{version}"
SOURCE_DATE = "{date}"
SOURCE_SHA256 = "{sha}"
ENTRIES = {len(pairs)}

_RAW = (
{body}
)
CONFUSABLES: dict[int, str] = {{int(p.split(":")[0], 16): p.split(":")[1] for p in _RAW.split()}}
'''


def main(argv: list[str]) -> int:
    args = [a for a in argv if not a.startswith("--")]
    if len(args) != 1:
        print(__doc__)
        return 3
    raw = Path(args[0]).read_bytes()
    pairs, version, date = parse(raw.decode("utf-8"))
    text = render(pairs, version, date, hashlib.sha256(raw).hexdigest())
    if "--check" in argv:
        sys.path.insert(0, str(ROOT / "src"))
        from intake import confusables_data as cd

        same = cd.CONFUSABLES == pairs and cd.SOURCE_SHA256 == hashlib.sha256(raw).hexdigest()
        print("committed data is current" if same else "committed data is STALE")
        return 0 if same else 1
    if "--write" in argv:
        TARGET.write_text(text, encoding="utf-8", newline=chr(10))
        print(f"wrote {TARGET} ({len(pairs)} entries)")
    else:
        sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
